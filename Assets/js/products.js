const productList = document.getElementById("productList");
const seedsContainer = document.getElementById("seedsContainer");

function renderSeeds(type) {
  const seeds = seedData[type] || [];
  seedsContainer.innerHTML = seeds.map(seed => `
    <div class="seed-card-alignment">
      <div class="seed-card">
        <img src="${seed.img}" alt="${seed.title}" />
        <div class="seed-info">
          <h3>${seed.title}</h3>
          ${seed.desc.map(d => `<p> <i class="fa-solid fa-angles-right" style="color:#f28b30; margin-right:0px;"></i> ${d}</p>`).join("")}
        </div>
      </div>
      </div>
    `).join('');
}

productList.addEventListener("click", e => {
  const li = e.target.closest("li");
  if (!li) return;
  document.querySelectorAll("#productList li").forEach(el => el.classList.remove("active"));
  li.classList.add("active");
  const type = li.dataset.type;
  renderSeeds(type);
});

function initFromURL() {
  const params = new URLSearchParams(window.location.search);
  const type = params.get("type");

  if (type && seedData[type]) {
    const allItems = document.querySelectorAll("#productList li");
    allItems.forEach(el => el.classList.remove("active"));

    const target = document.querySelector(`#productList li[data-type="${type}"]`);
    if (target) {
      target.classList.add("active");
      target.scrollIntoView({ behavior: "smooth", block: "center" });
    }
    renderSeeds(type);
  } else {
    const defaultType = document.querySelector("#productList li.active")?.dataset.type;
    if (defaultType) renderSeeds(defaultType);
  }
}

document.addEventListener("DOMContentLoaded", initFromURL);

